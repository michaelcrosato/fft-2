/** Title card + inscription + the sigil reminder for a Midnight Deep landing. */
function landing(name: string, subtitle: string, look: [number, number], riddle: string, extra: SceneCmd[] = []): SceneCmd[] {
  return [
    ['fade', 'out', 0.1],
    ['title', name, subtitle],
    ['fade', 'in', 1.2],
    ['music', 'dungeon'],
    ['camera', { at: look, zoom: 0.8, time: 3.0 }],
    ['narrate', `Cut into the stone above the stair, the letters run backwards: ${name}. Beneath them, smaller, in a hand no one living has seen: "${riddle}"`],
    ...extra,
    ['narrate', 'Somewhere upon this landing, a sigil lies hidden. Stand upon it, and the stair below will open.'],
  ];
}

